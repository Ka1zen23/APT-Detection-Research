export type Coordinates = [number, number, number];

export function placeNodes(graph: ProvenanceGraphData) {
  const normal = graph.nodes.find(({ kind }) => kind === "process") ?? graph.nodes[0];
  const peripheral = graph.nodes.filter(({ id }) => id !== normal?.id);
  const positions = new Map<string, Coordinates>();
  if (normal) positions.set(normal.id, [0, 0, 0]);
  peripheral.forEach(({ id }, index) => {
    const angle = Math.PI * 2 * index / peripheral.length + Math.PI * .22;
    const ring = peripheral.length > 12 && index % 2 === 1 ? .68 : 1;
    positions.set(id, [Math.cos(angle) * 3.9 * ring, Math.sin(angle) * 2.45 * ring, Math.sin(index * 2.2) * .84]);
  });
  return positions;
}

export function timestampGroups(edges: ProvenanceEdge[]) {
  if (!edges.length || edges.some(({ timestamp }) => timestamp == null || !Number.isFinite(timestamp))) return [];
  const values = [...new Set(edges.map(({ timestamp }) => timestamp!))].sort((a, b) => a - b);
  return values.length > 1 ? values.map((time) => ({
    time, edges: edges.filter(({ timestamp }) => timestamp === time).map(({ id }) => id),
  })) : [];
}
